public class ChaosRune {

    int id;
    String name;
    RuneElement element;
    double energyLevel;

    public ChaosRune(int id, String name, RuneElement element, double energyLevel) {
        this.id = id;
        this.name = name;
        this.element = element;
        this.energyLevel = energyLevel;
    }
}